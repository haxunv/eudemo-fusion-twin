"""Package complete, relative-path-preserving CAD and USD asset exports."""
import json
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
DEST = ASSETS / "downloads"


def main():
    DEST.mkdir(exist_ok=True)
    provenance = ASSETS / "source/provenance.json"
    with ZipFile(DEST / "cad.zip", "w", ZIP_DEFLATED) as archive:
        for path in sorted((ASSETS / "source/eudemo").glob("*/cad/*.stp")):
            archive.write(path, str(path.relative_to(ASSETS / "source/eudemo")))
        archive.write(provenance, "provenance.json")
        archive.writestr("README.txt", "Bluemira EU-DEMO-like concept CAD. Source models are single sectors, not a full 360-degree STEP assembly. The complete repeated assembly is supplied in the USD package. Units: metres. See provenance.json for source and limitations.")
    with ZipFile(DEST / "usd.zip", "w", ZIP_DEFLATED) as archive:
        for path in sorted((ASSETS / "scene").rglob("*")):
            if path.is_file():
                archive.write(path, str(path.relative_to(ASSETS)))
        archive.write(ASSETS / "manifest.json", "manifest.json")
        archive.write(provenance, "provenance.json")
        archive.writestr("README.txt", "Open scene/fusion.usda in an OpenUSD/Omniverse application. Keep the scene folder and its layers together. Units: metres; Z up. This archive contains conceptual CAD assembly geometry; runtime field overlays are generated by the application.")
    print(json.dumps({p.name: p.stat().st_size for p in DEST.glob("*.zip")}))


if __name__ == "__main__":
    main()
